CREATE VIEW order_details AS
SELECT o.order_id, o.order_date, c.customer_id, c.customer_name, c.region,
       cat.category_name AS category, s.subcategory_name AS sub_category,
       p.product_name, o.quantity, o.unit_price, o.total_price
FROM orders o
JOIN customers c      ON c.customer_id     = o.customer_id
JOIN products p       ON p.product_id      = o.product_id
JOIN subcategories s  ON s.subcategory_id  = p.subcategory_id
JOIN categories cat   ON cat.category_id   = s.category_id;
COMMIT;
